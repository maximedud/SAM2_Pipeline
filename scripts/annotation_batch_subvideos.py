class SubvideoState:
    def __init__(self):
        self.cap = None
        self.video_path = None
        self.name = None
        self.seg_type = None
        self.order = None
        self.origin_start = None
        self.origin_end = None
        self.total_frames = 0
        self.fps = 0.0
        self.current_frame_idx = 0
        self.original_frame = None
        self.frame = None
        self.annotations = {"objects": {}}

    def reset_annotations(self):
        self.annotations = {"objects": {}}


state = SubvideoState()

active_obj_id   = 1
box_mode        = False
box_drawing     = False
box_start       = None
box_current     = None
save_counter    = 0


