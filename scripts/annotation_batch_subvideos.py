def annotation_path_new(item_or_state) -> Path:
    """New convention: data/annotations/<subvideo_name>.json
    data/annotation_previews/*.jpg"""
    name = item_or_state["name"] if isinstance(item_or_state, dict) else item_or_state.name
    return ANNOTATION_DIR / f"{name}.json"


def annotation_path_old(item_or_state) -> Path:
    """Old convention: data/annotations/<order>_<name>_<type>.json"""
    if isinstance(item_or_state, dict):
        order = int(item_or_state["order"])
        name = item_or_state["name"]
        seg_type = item_or_state["type"]
    else:
        order = int(item_or_state.order)
        name = item_or_state.name
        seg_type = item_or_state.seg_type
    return ANNOTATION_DIR / f"{order:08d}_{name}_{seg_type}.json"


def empty_annotation_payload() -> dict:
    return {"objects": {}}


def normalize_loaded_annotations(payload: dict) -> dict:
    """Keep only the useful annotation content and make sure objects/prompts exist."""
    if not isinstance(payload, dict):
        return empty_annotation_payload()

    objects = payload.get("objects", {})
    if not isinstance(objects, dict):
        objects = {}

    normalized = {"objects": objects}

    for obj_key, obj_data in list(normalized["objects"].items()):
        if not isinstance(obj_data, dict):
            normalized["objects"][obj_key] = {"label": f"object_{obj_key}", "prompts": []}
            continue
        obj_data.setdefault("label", f"object_{obj_key}")
        obj_data.setdefault("prompts", [])
        if not isinstance(obj_data["prompts"], list):
            obj_data["prompts"] = []

        for p in obj_data["prompts"]:
            p.setdefault("points", [])
            p.setdefault("labels", [])
            p.setdefault("box", None)

    return normalized


def load_existing_annotation_for_item(item: dict) -> dict:
    """Load existing annotation if available. New name has priority, old name is fallback."""
    new_path = annotation_path_new(item)
    old_path = annotation_path_old(item)

    if new_path.exists():
        path = new_path
    elif old_path.exists():
        path = old_path
    else:
        print(f"No existing annotation for {item['name']} -> starting empty.")
        return empty_annotation_payload()

    try:
        with open(path, "r", encoding="utf-8") as f:
            payload = json.load(f)
    except JSONDecodeError as error:
        raise RuntimeError(f"Invalid annotation JSON: {path}") from error

    print(f"Loaded existing annotation: {path}")
    return normalize_loaded_annotations(payload)


def count_prompts(ann: dict) -> int:
    return sum(len(obj.get("prompts", [])) for obj in ann.get("objects", {}).values())


# -----------------------------------------------------------------------
# Annotation helpers (operate on state.annotations)
# -----------------------------------------------------------------------

def ensure_object_entry(obj_id: int):
    obj_key = str(obj_id)
    if obj_key not in state.annotations["objects"]:
        state.annotations["objects"][obj_key] = {
            "label": f"object_{obj_id}",
            "prompts": []
        }


def get_prompt_entry(obj_id: int, frame_idx: int):
    ensure_object_entry(obj_id)
    obj_key = str(obj_id)
    prompts = state.annotations["objects"][obj_key]["prompts"]

    for prompt in prompts:
        if int(prompt["frame"]) == int(frame_idx):
            return prompt

    new_prompt = {"frame": int(frame_idx), "points": [], "labels": [], "box": None}
    prompts.append(new_prompt)
    return new_prompt


# -----------------------------------------------------------------------
# Video / frame loading
# -----------------------------------------------------------------------

def load_subvideo(item: dict) -> bool:
    """Open a sub-video and reset state for annotation."""
    if state.cap is not None:
        state.cap.release()

    state.cap = cv2.VideoCapture(str(item["path"]))
    if not state.cap.isOpened():
        print(f"Could not open: {item['path']}")
        return False

    state.video_path        = item["path"]
    state.name              = item["name"]
    state.seg_type          = item["type"]
    state.order             = item["order"]
    state.origin_start      = item.get("origin_start_frame")
    state.origin_end        = item.get("origin_end_frame")
    state.total_frames      = int(state.cap.get(cv2.CAP_PROP_FRAME_COUNT))
    state.fps               = state.cap.get(cv2.CAP_PROP_FPS)
    state.current_frame_idx = 0

    # APPEND MODE: load existing annotations instead of resetting them.
    state.annotations = load_existing_annotation_for_item(item)
    print(f"Current loaded prompts: {count_prompts(state.annotations)}")

    # For video segments, start on frame 5 when possible to avoid unstable black/empty first frames.
    start_frame = (
        DEFAULT_VIDEO_START_FRAME
        if state.seg_type == "video"
        and state.total_frames > DEFAULT_VIDEO_START_FRAME
        else 0
    )
    return load_frame(start_frame)


def load_frame(frame_idx: int) -> bool:
    if frame_idx < 0:
        frame_idx = 0
    if frame_idx >= state.total_frames:
        frame_idx = state.total_frames - 1

    state.cap.set(cv2.CAP_PROP_POS_FRAMES, frame_idx)
    ret, img = state.cap.read()
    if not ret:
        print(f"Error: could not read frame {frame_idx}.")
        return False

    state.current_frame_idx = int(frame_idx)
    state.original_frame    = img.copy()
    state.frame             = img.copy()
    return True


# -----------------------------------------------------------------------
# Drawing
# -----------------------------------------------------------------------

def draw_annotations(img):
    out = img.copy()

    for obj_key, obj_data in state.annotations["objects"].items():
        obj_id = int(obj_key)
        color  = get_obj_color(obj_id)

        for prompt in obj_data["prompts"]:
            if int(prompt["frame"]) != int(state.current_frame_idx):
                continue

            for (x, y), label in zip(prompt["points"], prompt["labels"]):
                x, y = int(x), int(y)
                if int(label) == 1:
                    cv2.circle(out, (x, y), 6, color, -1)
                else:
                    cv2.circle(out, (x, y), 6, color, 2)
                    cv2.line(out, (x - 5, y - 5), (x + 5, y + 5), color, 2)
                    cv2.line(out, (x - 5, y + 5), (x + 5, y - 5), color, 2)
                cv2.putText(out, f"obj {obj_id}", (x + 8, y - 8),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.45, color, 1, cv2.LINE_AA)

            if prompt["box"] is not None:
                x1, y1, x2, y2 = [int(v) for v in prompt["box"]]
                cv2.rectangle(out, (x1, y1), (x2, y2), color, 2)
                cv2.putText(out, f"box obj {obj_id}", (x1, y1 - 6),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.45, color, 1, cv2.LINE_AA)

    if box_drawing and box_start and box_current:
        color = get_obj_color(active_obj_id)
        cv2.rectangle(out, box_start, box_current, color, 1)

    return out


def update_window_title():
    mode = " [BOX MODE]" if box_mode else ""
    nav  = "" if state.seg_type == "static" else f" | frame={state.current_frame_idx}/{state.total_frames-1}"
    cv2.setWindowTitle(
        "Batch Annotation Tool",
        f"[{state.seg_type.upper()}] {state.name}{nav} | active_obj={active_obj_id}{mode}"
    )


def show_current_frame():
    vis = state.original_frame.copy()
    image_rgb = cv2.cvtColor(state.original_frame, cv2.COLOR_BGR2RGB)
    image_predictor.set_image(image_rgb)

    with torch.inference_mode():
        autocast_context = (
            torch.autocast(device_type="cuda", dtype=torch.bfloat16)
            if DEVICE == "cuda" else
            torch.autocast(device_type="cpu", enabled=False)
        )
        with autocast_context:
            for obj_key, obj_data in state.annotations["objects"].items():
                obj_id = int(obj_key)
                color  = get_obj_color(obj_id)

                for prompt in obj_data["prompts"]:
                    if int(prompt["frame"]) != int(state.current_frame_idx):
                        continue

                    points = prompt["points"]
                    labels = prompt["labels"]
                    box    = prompt["box"]

                    if len(points) == 0 and box is None:
                        continue

                    point_coords = np.array(points, dtype=np.float32) if points else None
                    point_labels = np.array(labels, dtype=np.int32)   if labels else None
                    box_array    = np.array(box, dtype=np.float32)    if box is not None else None

                    masks, scores, _ = image_predictor.predict(
                        point_coords=point_coords,
                        point_labels=point_labels,
                        box=box_array,
                        multimask_output=True
                    )

                    best_idx = int(np.argmax(scores))
                    mask = masks[best_idx].astype(np.uint8)

                    overlay = vis.copy()
                    overlay[mask > 0] = color
                    vis = cv2.addWeighted(overlay, 0.28, vis, 0.72, 0)

                    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
                    cv2.drawContours(vis, contours, -1, color, 2)

    state.frame = draw_annotations(vis)

    header = f"[{state.seg_type.upper()}] {state.name}"
    if state.seg_type == "video":
        header += f" | frame {state.current_frame_idx}/{state.total_frames - 1}"
    header += f" | obj {active_obj_id}" + (" | BOX MODE" if box_mode else "")

    cv2.putText(state.frame, header, (10, 25),
                cv2.FONT_HERSHEY_SIMPLEX, 0.65, (255, 255, 255), 2, cv2.LINE_AA)

    update_window_title()
    cv2.imshow("Batch Annotation Tool", state.frame)


