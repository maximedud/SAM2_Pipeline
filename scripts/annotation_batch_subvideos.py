OBJECT_COLORS = {
    1: (0, 255, 0),     2: (255, 0, 0),     3: (0, 0, 255),
    4: (255, 255, 0),   5: (255, 0, 255),   6: (0, 255, 255),
    7: (128, 255, 0),   8: (255, 128, 0),   9: (128, 0, 255),
    10: (0, 128, 255),  11: (255, 0, 128),  12: (0, 255, 128),
    13: (128, 128, 255),14: (255, 128, 128),15: (128, 255, 255),
    16: (200, 200, 0),  17: (0, 200, 200),  18: (200, 0, 200),
}

def get_obj_color(obj_id: int):
    return OBJECT_COLORS.get(obj_id, (200, 200, 200))


# Shift+1 .. Shift+9 → objects 10..18
# On most layouts, Shift+digit produces these ASCII characters:
#   Shift+1 -> ! (33)   Shift+2 -> @ (64)   Shift+3 -> # (35)
#   Shift+4 -> $ (36)   Shift+5 -> % (37)   Shift+6 -> ^ (94)
#   Shift+7 -> & (38)   Shift+8 -> * (42)   Shift+9 -> ( (40)
# NOTE: this mapping is for a US/QWERTY layout. On AZERTY the symbols
# produced by Shift+digit differ — if objects 10-18 don't trigger
# correctly, run this once to find your actual key codes:
#     python -c "import cv2; cv2.namedWindow('t'); print(cv2.waitKey(0))"
# and adjust the dict below accordingly.
SHIFT_DIGIT_KEYS = {
    ord("!"): 10,
    ord("@"): 11,
    ord("#"): 12,
    ord("$"): 13,
    ord("%"): 14,
    ord("^"): 15,
    ord("&"): 16,
    ord("*"): 17,
    ord("("): 18,
}


