# Main program
# ---------------------------------------------------------------------------

def main():
    """Initialize SAM2 and run the batch annotation interface."""
    global image_predictor, active_obj_id, box_mode

    print("=" * 60)
    print("Batch Annotation Tool - Subvideos")
    print("=" * 60)

    if not SUBVIDEOS_DIR.exists():
        raise FileNotFoundError(f"Subvideos folder not found: {SUBVIDEOS_DIR}")
    if not CHECKPOINT_PATH.exists():
        raise FileNotFoundError(f"Checkpoint not found: {CHECKPOINT_PATH}")

    print("Loading SAM2 image predictor...")
    image_model = build_sam2(MODEL_CONFIG, str(CHECKPOINT_PATH), device=DEVICE)
    image_model = image_model.float()
    image_predictor = SAM2ImagePredictor(image_model)
    print("SAM2 image predictor loaded.")

    subvideo_list = build_subvideo_list()
    print(f"\nFound {len(subvideo_list)} sub-videos to annotate (chronological order).")
    for it in subvideo_list[:10]:
        print(f"  [{it['type']:6s}] {it['name']}")
    if len(subvideo_list) > 10:
        print(f"  ... and {len(subvideo_list) - 10} more")
    print()

    if not subvideo_list:
        raise RuntimeError("No sub-videos found.")

    cv2.namedWindow("Batch Annotation Tool")
    cv2.setMouseCallback("Batch Annotation Tool", mouse_callback)

    current_idx = 0
    if not load_subvideo(subvideo_list[current_idx]):
        raise RuntimeError("Could not load first sub-video.")
    show_current_frame()

    print("Keyboard commands:")
    print("  Navigation (video type only): q/d ±1 | a/e ±5 | b/f ±25 | j/l ±50 frames")
    print("  Objects: 1-9 select (1-9) | Shift+1-9 select (10-18) | left click=+ | right click=- | hold x+drag=box")
    print("  s : save/append THIS sub-video and move to NEXT")
    print("  n : skip to next WITHOUT saving")
    print("  p : go back to PREVIOUS sub-video")
    print("  u : remove last point | c : clear box | r : reset object on this frame")
    print("  v : save debug preview image")
    print("  ESC : quit")
    print()

    while True:
        key = cv2.waitKey(0) & 0xFF

        if key == 27:  # ESC
            break

        elif ord("1") <= key <= ord("9"):
            active_obj_id = key - ord("0")
            print(f"Active object = {active_obj_id}")
            show_current_frame()

        elif key in SHIFT_DIGIT_KEYS:
            active_obj_id = SHIFT_DIGIT_KEYS[key]
            print(f"Active object = {active_obj_id} (shift)")
            show_current_frame()

        elif key == ord("x"):
            box_mode = not box_mode
            print(f"Box mode: {'ON' if box_mode else 'OFF'}")
            update_window_title()

        elif key == ord("q"):
            change_frame(state.current_frame_idx - 1)
        elif key == ord("d"):
            change_frame(state.current_frame_idx + 1)
        elif key == ord("a"):
            change_frame(state.current_frame_idx - 5)
        elif key == ord("e"):
            change_frame(state.current_frame_idx + 5)
        elif key == ord("b"):
            change_frame(state.current_frame_idx - 25)
        elif key == ord("f"):
            change_frame(state.current_frame_idx + 25)
        elif key == ord("j"):
            change_frame(state.current_frame_idx - 50)
        elif key == ord("l"):
            change_frame(state.current_frame_idx + 50)

        elif key == ord("u"):
            remove_last_point()
        elif key == ord("c"):
            clear_box()
        elif key == ord("r"):
            reset_current_frame_annotations()
        elif key == ord("v"):
            save_current_view()

        elif key == ord("s"):
            save_current_subvideo()
            current_idx += 1
            if current_idx >= len(subvideo_list):
                print("All sub-videos processed!")
                break
            load_subvideo(subvideo_list[current_idx])
            show_current_frame()
            print(f"\n--- Now annotating [{current_idx+1}/{len(subvideo_list)}]: {state.name} ({state.seg_type}) ---")

        elif key == ord("n"):
            print(f"Skipped {state.name} without saving.")
            current_idx += 1
            if current_idx >= len(subvideo_list):
                print("Reached end of list.")
                break
            load_subvideo(subvideo_list[current_idx])
            show_current_frame()
            print(f"\n--- Now annotating [{current_idx+1}/{len(subvideo_list)}]: {state.name} ({state.seg_type}) ---")

        elif key == ord("p"):
            if current_idx > 0:
                current_idx -= 1
                load_subvideo(subvideo_list[current_idx])
                show_current_frame()
                print(f"\n--- Back to [{current_idx+1}/{len(subvideo_list)}]: {state.name} ({state.seg_type}) ---")
            else:
                print("Already at first sub-video.")

    cv2.destroyAllWindows()
    if state.cap is not None:
        state.cap.release()
    print("Batch annotation ended.")


if __name__ == "__main__":
    main()

