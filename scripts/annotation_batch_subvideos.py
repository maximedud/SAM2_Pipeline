def add_point(x: int, y: int, label: int):
    prompt = get_prompt_entry(active_obj_id, state.current_frame_idx)
    prompt["points"].append([int(x), int(y)])
    prompt["labels"].append(int(label))
    sign = "+" if int(label) == 1 else "-"
    print(f"[{state.name}] obj {active_obj_id} | frame {state.current_frame_idx} | point {sign}: ({x},{y})")
    show_current_frame()


def set_box(x1, y1, x2, y2):
    bx1, bx2 = min(x1, x2), max(x1, x2)
    by1, by2 = min(y1, y2), max(y1, y2)
    if abs(bx2 - bx1) < 5 or abs(by2 - by1) < 5:
        print("Box too small, ignored.")
        return
    prompt = get_prompt_entry(active_obj_id, state.current_frame_idx)
    prompt["box"] = [bx1, by1, bx2, by2]
    print(f"[{state.name}] obj {active_obj_id} | frame {state.current_frame_idx} | box: [{bx1},{by1},{bx2},{by2}]")
    show_current_frame()


def clear_box():
    obj_key = str(active_obj_id)
    if obj_key not in state.annotations["objects"]:
        return
    for prompt in state.annotations["objects"][obj_key]["prompts"]:
        if int(prompt["frame"]) == int(state.current_frame_idx):
            prompt["box"] = None
    show_current_frame()


def remove_last_point():
    obj_key = str(active_obj_id)
    if obj_key not in state.annotations["objects"]:
        return
    for prompt in state.annotations["objects"][obj_key]["prompts"]:
        if int(prompt["frame"]) == int(state.current_frame_idx):
            if prompt["points"]:
                prompt["points"].pop()
                prompt["labels"].pop()
            break
    show_current_frame()


def reset_current_frame_annotations():
    obj_key = str(active_obj_id)
    if obj_key not in state.annotations["objects"]:
        return
    state.annotations["objects"][obj_key]["prompts"] = [
        p for p in state.annotations["objects"][obj_key]["prompts"]
        if int(p["frame"]) != int(state.current_frame_idx)
    ]
    show_current_frame()


def change_frame(new_idx: int):
    if state.seg_type == "static":
        print("Static segment: navigation disabled (single frame only).")
        return
    if load_frame(new_idx):
        show_current_frame()


def save_current_view():
    global save_counter
    out_path = PREVIEW_DIR / f"preview_{state.name}_{state.current_frame_idx}_{save_counter}.jpg"
    cv2.imwrite(str(out_path), state.frame)
    print(f"Preview saved: {out_path}")
    save_counter += 1


# -----------------------------------------------------------------------
# Save current sub-video annotation
# -----------------------------------------------------------------------

def save_current_subvideo():
    """
    Save annotation for the current sub-video.

    Existing prompts are preserved because they are loaded when the subvideo
    is opened. The updated annotation is saved with the final naming
    convention: data/annotations/<name>.json.
    """
    out_path = annotation_path_new(state)

    payload = {
        "subvideo_path":      str(state.video_path),
        "name":                state.name,
        "type":                state.seg_type,
        "order":               state.order,
        "origin_start_frame":  state.origin_start,
        "origin_end_frame":    state.origin_end,
        "fps":                 state.fps,
        "total_frames":        state.total_frames,
        "updated_at":          datetime.now().strftime("%Y%m%d_%H%M%S"),
        "objects":             state.annotations.get("objects", {}),
    }

    if state.seg_type == "static":
        payload["annotated_frame"] = state.current_frame_idx

    for obj_data in payload["objects"].values():
        obj_data.setdefault("prompts", [])
        obj_data["prompts"] = sorted(obj_data["prompts"], key=lambda p: int(p["frame"]))

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)

    print(f"Saved: {out_path}")
    print(f"Total prompts now: {count_prompts(payload)}")


# -----------------------------------------------------------------------
# Mouse callback
# -----------------------------------------------------------------------

def mouse_callback(event, x, y, flags, param):
    global box_drawing, box_start, box_current

    if box_mode:
        if event == cv2.EVENT_LBUTTONDOWN:
            box_drawing = True
            box_start   = (x, y)
            box_current = (x, y)
        elif event == cv2.EVENT_MOUSEMOVE and box_drawing:
            box_current = (x, y)
            preview = draw_annotations(state.original_frame.copy())
            cv2.imshow("Batch Annotation Tool", preview)
        elif event == cv2.EVENT_LBUTTONUP and box_drawing:
            box_drawing = False
            if box_start and box_current:
                set_box(box_start[0], box_start[1], box_current[0], box_current[1])
            box_start = None
            box_current = None
    else:
        if event == cv2.EVENT_LBUTTONDOWN:
            add_point(x, y, label=1)
        elif event == cv2.EVENT_RBUTTONDOWN:
            add_point(x, y, label=0)


