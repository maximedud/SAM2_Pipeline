# -----------------------------------------------------------------------
# Type detection
# -----------------------------------------------------------------------
#
# Filenames follow the convention: <name>_<start>_<end>.mp4
# where <name> often starts with a type hint:
#   "texte_", "question_", "matrice_" → static
#   "video_", "acteur_"               → video
#
# If index.json exists (written by video_explorer.py), it takes priority
# since it stores the type explicitly per filename.

STATIC_PREFIXES = ("texte_", "question_", "matrice_")
VIDEO_PREFIXES  = ("video_", "acteur_")


def load_index() -> dict:
    """Load index.json as {filename: entry} for fast lookup."""
    index_path = SUBVIDEOS_DIR / "index.json"
    if not index_path.exists():
        return {}
    try:
        with open(index_path, "r", encoding="utf-8") as f:
            entries = json.load(f)
    except JSONDecodeError as error:
        raise RuntimeError(f"Invalid JSON index: {index_path}") from error

    if not isinstance(entries, list):
        raise RuntimeError(f"Expected a list in index file: {index_path}")

    return {
        entry["filename"]: entry
        for entry in entries
        if isinstance(entry, dict) and "filename" in entry
    }


def detect_type(filename: str, index: dict) -> str:
    """Return 'static' or 'video' for a given filename."""
    if filename in index:
        return index[filename].get("type", "video")

    lower = filename.lower()
    if lower.startswith(STATIC_PREFIXES):
        return "static"
    if lower.startswith(VIDEO_PREFIXES):
        return "video"

    print(f"  WARNING: could not detect type for '{filename}', defaulting to 'video'.")
    return "video"


def get_order(filename: str, index: dict, fallback_idx: int) -> int:
    """Return chronological order rank for a filename."""
    if filename in index and "start_frame" in index[filename]:
        return index[filename]["start_frame"]
    return fallback_idx * 1_000_000  # arbitrary large fallback spacing


def build_subvideo_list() -> list:
    index = load_index()
    mp4_files = sorted(SUBVIDEOS_DIR.glob("*.mp4"))

    items = []
    for i, path in enumerate(mp4_files):
        seg_type = detect_type(path.name, index)
        order    = get_order(path.name, index, i)
        entry    = index.get(path.name, {})
        items.append({
            "path": path,
            "name": path.stem,
            "type": seg_type,
            "order": order,
            "origin_start_frame": entry.get("start_frame"),
            "origin_end_frame": entry.get("end_frame"),
        })

    items.sort(key=lambda it: it["order"])
    return items


