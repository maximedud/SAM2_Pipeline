"""
Interactive batch annotation tool for static and dynamic subvideos.

This script is the second step of the segmentation pipeline. It browses the
subvideos generated by exploration_extraction.py, determines whether each
segment is static or dynamic, and lets the user create or refine SAM2
prompts through an interactive OpenCV interface.

For every subvideo, the tool can load existing annotations, preserve and
edit previous prompts, add positive or negative points and boxes, display
a live SAM2 preview, and save the updated annotation using the final naming
convention.

Static segments are annotated on one representative frame. Dynamic
segments can be annotated on several frames before later propagation.

Purpose:

Purpose:
    - Browse all subvideos inside data/subvideos/.
    - For each sub-video, detect its type from index.json (or filename prefix):
          "static" → annotate ONE representative frame (mask + json)
          "video"  → annotate prompts that will later be propagated by script 2
    - Live SAM2 mask preview (points + box prompts), same as before.
    - Move to the next/previous sub-video without restarting the script.
    - Load an existing annotation JSON when available and update it without losing previous prompts.

Input:
    data/subvideos/*.mp4
    data/subvideos/index.json   (optional, used to read declared type + order)
    SAM_2/checkpoints/sam2.1_hiera_small.pt

Output:
    data/annotations/<subvideo_name>.json
    data/annotation_previews/*.jpg

    Example:
        data/annotations/video_task3_10.json

    Backward compatibility:
        If an old annotation file exists with the previous naming pattern
        <order>_<name>_<type>.json, it is loaded and then saved using the new name.

Keyboard commands:
    Navigation inside current sub-video (video type only):
        q : previous frame
        d : next frame
        a : -5 frames
        e : +5 frames
        b : -25 frames
        f : +25 frames
        j : -50 frames
        l : +50 frames

    Objects:
        1-9 : select active object
        left click          : positive point
        right click         : negative point
        hold x + drag left  : draw box prompt

    Actions:
        s    : save/append annotation for THIS sub-video and move to NEXT one
        v    : save current visual preview (debug)
        u    : remove last point for active object on current frame
        c    : clear box for active object on current frame
        r    : reset ALL annotations for active object on current frame
        n    : skip to next sub-video WITHOUT saving
        p    : go back to previous sub-video
        ESC  : quit entirely
"""

