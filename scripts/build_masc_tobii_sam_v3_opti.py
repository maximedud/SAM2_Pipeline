#!/usr/bin/env python3
"""
build_masc_tobii_sam_v3_opti.py

PURPOSE
-------
Synchronize real Tobii eye-tracking data from MASC participants with
SAM 2 segmentation masks generated from a reference participant (P6).

For each Tobii gaze sample, the script identifies the corresponding
reference video frame and determines whether the gaze falls on a
segmented object, the background, or outside the image.

INPUT DATA AND DIRECTORY STRUCTURE
----------------------------------
Expected project structure:

projet_SAM/
├── data/
│   ├── propagations/
│   │   └── video_task3_X/
│   │       ├── metadata.json
│   │       └── masks/
│   │           ├── obj_01/
│   │           │   └── frame_000000.png
│   │           └── obj_02/
│   │               └── frame_000000.png
│   └── static_segmentations/
│       └── question_task3_X/
│           ├── metadata.json
│           └── masks/
│               └── *.png
├── MASC/
│   └── derived/
└── SAM_2/
    └── scripts/

Tobii data are loaded separately from:

    ~/Downloads/DatasetRed/PXX/byTASK/MASC/PXX_MASC_Tobii.csv

IMPORTANT: DatasetRed is a machine-specific, external data directory.
The DATASET_RED variable must be adapted if the dataset is stored
elsewhere. These participant data should not be uploaded to a public
GitHub repository.

MASC EVENT MAPPING
------------------
The script recognizes the following Tobii event names:

    MASC VideoX      -> video_task3_X
    MASC QuestionVX  -> question_task3_X

Other events, including MASC IntroX, are not processed as SAM
segments. Unrecognized events and event anomalies are reported
in unmapped_events.csv.

TEMPORAL SYNCHRONIZATION
------------------------
The SAM segmentation of participant P6 is used as the reference
for the other MASC participants.

Tobii samples are mapped proportionally from the duration of each
participant's recorded event to the number of frames in the
corresponding reference segment.

This allows participants with slightly different event durations
to share the same reference segmentation.

IMPORTANT: This is a proportional temporal alignment, not an exact
frame-by-frame synchronization of independently recorded videos.
It assumes that the visual content and its progression are
sufficiently comparable across participants.

Static segments use a single reference frame (frame 0).

GAZE COORDINATES
----------------
Gaze coordinates can be provided as normalized coordinates or pixels.

The script supports automatic coordinate-mode detection, as well as
explicit source-screen dimensions when rescaling is required.

Correct screen dimensions and coordinate conventions are essential
for reliable gaze-to-object matching.

MASK INTERPRETATION
-------------------
For each reference frame, the script reads the available SAM masks
and tests the gaze coordinates against their actual pixels.

    gazed_objects:
        Object identifiers whose masks contain the gaze point.

    background:
        Valid gaze coordinates that do not intersect any available
        object mask.

    out_of_bounds:
        Gaze coordinates outside the reference image.

    objects_present:
        Objects for which a readable mask file exists at that frame.

IMPORTANT: objects_present does not guarantee that the corresponding
mask contains nonzero pixels. Actual gaze hits are determined using
the mask pixel values.

PROCESSING AND OPTIMIZATION
---------------------------
- Masks are loaded only when required.
- No global mask cache is maintained.
- Frames are processed using a configurable worker pool.
- Masks are released after processing.
- Per-segment checkpoints allow interrupted processing to resume.
- Progress information and estimated remaining time are displayed.
- objects.csv is not generated by this script.

OUTPUTS
-------
Results are saved under:

    MASC/derived/tobii_sam_v3_opti/participants/PXX/

Main outputs:

    segments.csv
        Recognized MASC events, temporal intervals and SAM references.

    unmapped_events.csv
        Unrecognized events and event anomalies.

    raw_enriched/gaze_samples.csv
        Tobii samples enriched with reference frames and gaze-object
        intersections.

    gaze.csv
        Aggregated gaze information for each reference frame.

    qc_report.csv
        Participant-level quality-control indicators, including
        valid gaze percentage, object hits, background observations
        and out-of-bounds coordinates.

A global summary is also generated:

    MASC/derived/tobii_sam_v3_opti/all_participants_summary.csv

EXECUTION EXAMPLES
------------------
Process one participant:

    python build_masc_tobii_sam_v3_opti.py --participant P01

Process all available participants:

    python build_masc_tobii_sam_v3_opti.py --all

Resume interrupted processing:

    python build_masc_tobii_sam_v3_opti.py --participant P01 --resume

Reduce parallel processing:

    python build_masc_tobii_sam_v3_opti.py --participant P01 --workers 2

REPRODUCIBILITY AND LIMITATIONS
-------------------------------
This script is part of a reproducible research pipeline combining
SAM 2 segmentation and Tobii eye-tracking measurements.

Reproducing the results requires:
- The reference SAM masks and associated metadata.
- The original Tobii data.
- Consistent MASC event naming.
- Correct gaze coordinate dimensions.
- The same temporal alignment methodology.

The quality of the resulting measurements depends on the accuracy
of the SAM masks, the validity of the Tobii recordings and the
assumptions used to align participant recordings.

Quality-control reports should be reviewed before interpreting
or reusing the resulting gaze measurements.
"""

