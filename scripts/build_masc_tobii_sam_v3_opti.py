def tic():
    return time.perf_counter()


def fmt_time(sec):
    sec = int(max(0, sec))
    if sec < 60:
        return f"{sec}s"
    m, s = divmod(sec, 60)
    if m < 60:
        return f"{m}m{s:02d}s"
    h, m = divmod(m, 60)
    return f"{h}h{m:02d}m"


def norm_participant(v):
    s = str(v).strip().upper()
    if s.startswith("P"):
        s = s[1:]
    if not s.isdigit():
        raise ValueError(f"Participant invalide: {v!r}")
    return f"P{int(s):02d}"


def clean(v):
    return "" if pd.isna(v) else re.sub(r"\s+", " ", str(v).strip())


def read_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    except Exception:
        return {}


def object_id_from_path(path):
    if path.parent.name.startswith("obj_"):
        return path.parent.name
    m = re.search(r"(\d+)$", path.stem)
    return f"obj_{int(m.group(1)):02d}" if m else path.stem


def event_to_segment(value):
    s = clean(value)

    m = re.match(r"(?i)^MASC\s+Video\s*(\d+)(?:\s|\(|$)", s)
    if m:
        return f"video_task3_{int(m.group(1))}", "video", "video_number"

    m = re.match(r"(?i)^MASC\s+QuestionV\s*(\d+)(?:\s|\(|$)", s)
    if m:
        return f"question_task3_{int(m.group(1))}", "static", "question_number"

    return None, None, "unmapped_event_value"


def find_tobii(participant):
    p = DATASET_RED / participant / "byTASK" / "MASC" / f"{participant}_MASC_Tobii.csv"
    if not p.exists():
        raise FileNotFoundError(f"Tobii introuvable: {p}")
    return p


def load_tobii(path):
    print(f"[LOAD] {path}", flush=True)
    t0 = tic()
    df = pd.read_csv(path, sep=";", low_memory=False)

    required = ["timeSF", "Event", "EventValue", "GazePointX", "GazePointY"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise RuntimeError(f"Colonnes Tobii manquantes: {missing}")

    for c in ["timeSF", "timeTobiiSF", "GazePointX", "GazePointY"]:
        if c in df.columns:
            df[c] = pd.to_numeric(df[c], errors="coerce")

    df["Event"] = df["Event"].map(clean)
    df["EventValue"] = df["EventValue"].map(clean)
    print(f"[LOAD] {len(df):,} lignes en {fmt_time(tic()-t0)}", flush=True)
    return df


def extract_segments(df):
    ev = df[
        df["Event"].isin([URL_START, URL_END]) & df["timeSF"].notna()
    ].sort_values("timeSF")

    active = defaultdict(list)
    segments = []
    anomalies = []

    for _, r in ev.iterrows():
        typ = r["Event"]
        val = r["EventValue"]
        t = float(r["timeSF"])

        if typ == URL_START:
            active[val].append(t)
            continue

        if active[val]:
            start = active[val].pop()
            if t <= start:
                anomalies.append({
                    "event": typ, "event_value": val,
                    "timeSF": t, "reason": "end_before_start",
                })
                continue

            name, stype, reason = event_to_segment(val)
            segments.append({
                "event_value": val,
                "tobii_start_s": start,
                "tobii_end_s": t,
                "duration_s": t - start,
                "segment_name": name,
                "segment_type": stype,
                "mapping_reason": reason,
            })
        else:
            anomalies.append({
                "event": typ, "event_value": val,
                "timeSF": t, "reason": "end_without_start",
            })

    for val, starts in active.items():
        for t in starts:
            anomalies.append({
                "event": URL_START, "event_value": val,
                "timeSF": t, "reason": "start_without_end",
            })

    return pd.DataFrame(segments), pd.DataFrame(anomalies)


def reference_info(name, stype):
    if stype == "video":
        d = PROPAGATIONS_DIR / name
        meta = read_json(d / "metadata.json")
        n = int(meta.get("n_frames", 0) or 0)

        if n <= 0 and (d / "masks").exists():
            max_frame = -1
            for p in (d / "masks").glob("obj_*/frame_*.png"):
                m = re.search(r"frame_(\d+)\.png$", p.name)
                if m:
                    max_frame = max(max_frame, int(m.group(1)))
            if max_frame >= 0:
                n = max_frame + 1

        return {
            "reference_available": d.exists() and (d / "masks").exists() and n > 0,
            "reference_n_frames": n,
            "reference_width": int(meta.get("width", 1920) or 1920),
            "reference_height": int(meta.get("height", 1080) or 1080),
            "reference_fps": float(meta.get("fps", np.nan)),
        }

    d = STATIC_DIR / name
    meta = read_json(d / "metadata.json")
    masks = list((d / "masks").glob("*.png")) if (d / "masks").exists() else []

    return {
        "reference_available": d.exists() and bool(masks),
        "reference_n_frames": 1,
        "reference_width": int(meta.get("width", 1920) or 1920),
        "reference_height": int(meta.get("height", 1080) or 1080),
        "reference_fps": np.nan,
    }


def enrich_segments(df, participant):
    rows = []
    for i, r in df.reset_index(drop=True).iterrows():
        x = r.to_dict()
        x["participant"] = participant
        x["segment_index"] = i

        if pd.notna(x["segment_name"]) and pd.notna(x["segment_type"]):
            x.update(reference_info(str(x["segment_name"]), str(x["segment_type"])))
        else:
            x["segment_name"] = None
            x["segment_type"] = None
            x.update({
                "reference_available": False,
                "reference_n_frames": 0,
                "reference_width": np.nan,
                "reference_height": np.nan,
                "reference_fps": np.nan,
            })
        rows.append(x)
    return pd.DataFrame(rows)


def detect_gaze_mode(df, requested):
    if requested != "auto":
        return requested
    valid = df[["GazePointX", "GazePointY"]].dropna()
    if valid.empty:
        return "pixels"
    qx = valid["GazePointX"].abs().quantile(0.99)
    qy = valid["GazePointY"].abs().quantile(0.99)
    return "normalized" if qx <= 1.5 and qy <= 1.5 else "pixels"


def make_transform(df, requested, rw, rh, sw, sh):
    mode = detect_gaze_mode(df, requested)

    if mode == "normalized":
        # 1.0 doit correspondre au dernier pixel valide.
        return mode, float(max(rw - 1, 1)), float(max(rh - 1, 1)), ""

    if sw is not None and sh is not None:
        return mode, rw / float(sw), rh / float(sh), ""

    warning = (
        "pixel gaze assumed to use reference dimensions; "
        "set --gaze-source-width/height if different"
    )
    return mode, 1.0, 1.0, warning


def build_mask_index(name, stype):
    """
    Index léger : chemins seulement. Pas de PNG chargé en RAM.
    """
    if stype == "video":
        base = PROPAGATIONS_DIR / name / "masks"
        objects = []
        for d in sorted(base.glob("obj_*")):
            if d.is_dir():
                objects.append((d.name, d))
        return objects

    base = STATIC_DIR / name / "masks"
    return [(object_id_from_path(p), p) for p in sorted(base.glob("*.png"))]


def process_one_frame(job):
    """
    Worker d'une frame.

    IMPORTANT :
    - On ne fait aucun np.any(mask), donc pas de scan complet du masque.
    - Le masque est lu, les pixels de gaze sont testés, puis le tableau est libéré.
    """
    (
        rf, xs, ys, rw, rh, stype, mask_index
    ) = job

    n = len(xs)
    gazed = [""] * n
    out_bounds = np.zeros(n, dtype=bool)

    valid = np.isfinite(xs) & np.isfinite(ys)

    xi = np.zeros(n, dtype=np.int32)
    yi = np.zeros(n, dtype=np.int32)
    xi[valid] = np.rint(xs[valid]).astype(np.int32)
    yi[valid] = np.rint(ys[valid]).astype(np.int32)

    in_bounds = (
        valid
        & (xi >= 0) & (xi < rw)
        & (yi >= 0) & (yi < rh)
    )

    out_bounds[valid & ~in_bounds] = True

    for i in np.where(valid & ~in_bounds)[0]:
        gazed[i] = "out_of_bounds"

    valid_idx = np.where(in_bounds)[0]
    hits = [[] for _ in range(n)]
    present = []

    if len(valid_idx):
        px = xi[valid_idx]
        py = yi[valid_idx]

        for oid, source in mask_index:
            if stype == "video":
                p = source / f"frame_{int(rf):06d}.png"
                if not p.exists():
                    continue
            else:
                p = source

            mask = cv2.imread(str(p), cv2.IMREAD_GRAYSCALE)
            if mask is None:
                continue

            # FAST mode: existence of a decodable mask file = object listed as present.
            # Gaze hit itself remains exact because we inspect the real mask pixels.
            present.append(oid)

            h, w = mask.shape[:2]
            ok = (px < w) & (py < h)

            if np.any(ok):
                local_positions = np.where(ok)[0]
                vals = mask[py[ok], px[ok]]
                hit_pos = local_positions[vals > 0]

                for pos in hit_pos:
                    hits[int(valid_idx[pos])].append(oid)

            del mask

    for i in valid_idx:
        gazed[i] = "|".join(sorted(hits[int(i)])) if hits[int(i)] else "background"

    return int(rf), gazed, out_bounds, "|".join(sorted(set(present)))


def aggregate_frame_group(g, participant, name, stype, ref_frame):
    valid = g[g["gaze_valid"]]
    counts = Counter()

    for val in valid["gazed_objects"].fillna(""):
        if not val:
            continue
        if val in ("background", "out_of_bounds"):
            counts[val] += 1
        else:
            for obj in val.split("|"):
                if obj:
                    counts[obj] += 1

    if counts and len(valid):
        dom, dom_n = counts.most_common(1)[0]
        share = dom_n / len(valid)
    else:
        dom, share = "", np.nan

    present = sorted({
        obj
        for cell in g["objects_present"].fillna("")
        for obj in str(cell).split("|")
        if obj
    })

    return {
        "participant": participant,
        "segment_name": name,
        "segment_type": stype,
        "ref_frame": int(ref_frame),
        "n_tobii_samples": int(len(g)),
        "n_valid_gaze": int(len(valid)),
        "mean_gaze_x_px": valid["gaze_x_px"].mean() if len(valid) else np.nan,
        "mean_gaze_y_px": valid["gaze_y_px"].mean() if len(valid) else np.nan,
        "median_gaze_x_px": valid["gaze_x_px"].median() if len(valid) else np.nan,
        "median_gaze_y_px": valid["gaze_y_px"].median() if len(valid) else np.nan,
        "objects_present": "|".join(present),
        "dominant_gazed_object": dom,
        "dominant_gazed_object_share": share,
        "gaze_distribution": "|".join(f"{k}:{v}" for k, v in counts.most_common()),
        "background_samples": int(counts.get("background", 0)),
        "out_of_bounds_samples": int(counts.get("out_of_bounds", 0)),
        "reference_width": int(g["reference_width"].iloc[0]),
        "reference_height": int(g["reference_height"].iloc[0]),
        "coordinate_mode": str(g["coordinate_mode"].iloc[0]),
    }


