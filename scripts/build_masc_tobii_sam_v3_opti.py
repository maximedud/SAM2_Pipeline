def segment_checkpoint_paths(tmp_dir, segment_index, name):
    safe = re.sub(r"[^A-Za-z0-9_.-]+", "_", name)
    stem = f"{int(segment_index):03d}_{safe}"
    return (
        tmp_dir / f"{stem}_samples.csv",
        tmp_dir / f"{stem}_gaze.csv",
        tmp_dir / f"{stem}_meta.json",
    )


def process_participant(
    participant,
    gaze_mode,
    source_width,
    source_height,
    workers,
    progress_every,
    resume,
):
    participant = norm_participant(participant)
    total_start = tic()

    print("\n" + "=" * 100, flush=True)
    print(f"[START] {participant} | workers={workers} | resume={resume}", flush=True)
    print("=" * 100, flush=True)

    tobii = load_tobii(find_tobii(participant))

    raw_segments, anomalies = extract_segments(tobii)
    seg = enrich_segments(raw_segments, participant)

    out_dir = PARTICIPANTS_OUT / participant
    raw_dir = out_dir / "raw_enriched"
    tmp_dir = out_dir / "_segment_checkpoints"

    out_dir.mkdir(parents=True, exist_ok=True)
    raw_dir.mkdir(parents=True, exist_ok=True)

    if tmp_dir.exists() and not resume:
        shutil.rmtree(tmp_dir)
    tmp_dir.mkdir(parents=True, exist_ok=True)

    unmapped_rows = []

    for _, r in seg.iterrows():
        if pd.isna(r["segment_name"]):
            unmapped_rows.append({
                "event": "",
                "event_value": r["event_value"],
                "timeSF": r["tobii_start_s"],
                "reason": r["mapping_reason"],
            })

    if not anomalies.empty:
        unmapped_rows.extend(anomalies.to_dict("records"))

    unmapped = pd.DataFrame(
        unmapped_rows,
        columns=["event", "event_value", "timeSF", "reason"]
    )

    seg_cols = [
        "participant", "segment_index", "event_value",
        "segment_name", "segment_type",
        "tobii_start_s", "tobii_end_s", "duration_s",
        "mapping_reason", "reference_available",
        "reference_n_frames", "reference_width",
        "reference_height", "reference_fps",
    ]

    seg[seg_cols].to_csv(out_dir / "segments.csv", index=False)
    unmapped.to_csv(out_dir / "unmapped_events.csv", index=False)

    processable = seg[
        seg["segment_name"].notna()
        & seg["reference_available"].fillna(False)
    ].copy()

    print(
        f"[SEGMENTS] total={len(seg)} | mappés={seg['segment_name'].notna().sum()} | "
        f"SAM dispo={len(processable)} | unmapped/anomalies={len(unmapped)}",
        flush=True,
    )

    completed_before = 0
    for _, sr in processable.iterrows():
        sp, gp, mp = segment_checkpoint_paths(
            tmp_dir, sr["segment_index"], str(sr["segment_name"])
        )
        if resume and sp.exists() and gp.exists() and mp.exists():
            completed_before += 1

    if completed_before:
        print(
            f"[RESUME] {completed_before}/{len(processable)} segments déjà terminés seront sautés.",
            flush=True,
        )

    coordinate_warnings = set()
    n_segments = len(processable)
    session_done = 0
    session_times = []

    for seg_no, (_, sr) in enumerate(processable.iterrows(), start=1):
        name = str(sr["segment_name"])
        stype = str(sr["segment_type"])
        segment_index = int(sr["segment_index"])

        sample_cp, gaze_cp, meta_cp = segment_checkpoint_paths(
            tmp_dir, segment_index, name
        )

        if resume and sample_cp.exists() and gaze_cp.exists() and meta_cp.exists():
            print(
                f"[{seg_no:02d}/{n_segments:02d}] {name:<24} | CHECKPOINT OK -> skip",
                flush=True,
            )
            continue

        seg_start = tic()

        t0 = float(sr["tobii_start_s"])
        t1 = float(sr["tobii_end_s"])
        n_ref = int(sr["reference_n_frames"])
        rw = int(sr["reference_width"])
        rh = int(sr["reference_height"])

        sub = tobii[(tobii["timeSF"] >= t0) & (tobii["timeSF"] <= t1)].copy()

        mode, sx, sy, warning = make_transform(
            sub, gaze_mode, rw, rh, source_width, source_height
        )
        if warning:
            coordinate_warnings.add(warning)

        if sub.empty:
            print(f"[{seg_no:02d}/{n_segments:02d}] {name:<24} | 0 sample | SKIP", flush=True)
            continue

        duration = max(t1 - t0, 1e-12)
        sub["relative_position"] = ((sub["timeSF"] - t0) / duration).clip(0, 1)

        if stype == "static":
            sub["ref_frame"] = 0
        else:
            sub["ref_frame"] = np.rint(
                sub["relative_position"] * (n_ref - 1)
            ).astype(int)

        sub["participant"] = participant
        sub["segment_name"] = name
        sub["segment_type"] = stype
        sub["event_value"] = sr["event_value"]
        sub["tobii_start_s"] = t0
        sub["tobii_end_s"] = t1

        sub["gaze_x_raw"] = sub["GazePointX"]
        sub["gaze_y_raw"] = sub["GazePointY"]
        sub["gaze_x_px"] = sub["GazePointX"] * sx
        sub["gaze_y_px"] = sub["GazePointY"] * sy
        sub["gaze_valid"] = sub["gaze_x_px"].notna() & sub["gaze_y_px"].notna()
        sub["coordinate_mode"] = mode
        sub["reference_width"] = rw
        sub["reference_height"] = rh
        sub["scale_x"] = sx
        sub["scale_y"] = sy
        sub["objects_present"] = ""
        sub["gazed_objects"] = ""
        sub["gaze_out_of_bounds"] = False

        unique_frames = sorted(sub["ref_frame"].dropna().astype(int).unique())
        frame_total = len(unique_frames)
        mask_index = build_mask_index(name, stype)

        print(
            f"[{seg_no:02d}/{n_segments:02d}] {name:<24} | "
            f"samples={len(sub):,} | frames={frame_total:,} | objets={len(mask_index)}",
            flush=True,
        )

        jobs = []
        frame_to_indices = {}

        for rf in unique_frames:
            idx = sub.index[sub["ref_frame"] == rf].to_numpy()
            frame_to_indices[int(rf)] = idx
            xs = sub.loc[idx, "gaze_x_px"].to_numpy(dtype=float)
            ys = sub.loc[idx, "gaze_y_px"].to_numpy(dtype=float)
            jobs.append((int(rf), xs, ys, rw, rh, stype, mask_index))

        frame_done = 0
        with ThreadPoolExecutor(max_workers=workers) as executor:
            for rf, gazed, oob, present in executor.map(process_one_frame, jobs):
                idx = frame_to_indices[rf]

                sub.loc[idx, "objects_present"] = present
                sub.loc[idx, "gazed_objects"] = gazed
                sub.loc[idx, "gaze_out_of_bounds"] = oob

                frame_done += 1

                if (
                    frame_done == 1
                    or frame_done % progress_every == 0
                    or frame_done == frame_total
                ):
                    elapsed = tic() - seg_start
                    rate = frame_done / elapsed if elapsed > 0 else 0
                    remaining = frame_total - frame_done
                    eta = remaining / rate if rate > 0 else 0

                    overall_done = (seg_no - 1) + frame_done / max(frame_total, 1)
                    overall_pct = 100 * overall_done / max(n_segments, 1)

                    print(
                        f"    [FRAME] {frame_done:>5}/{frame_total:<5} "
                        f"({100*frame_done/frame_total:5.1f}%) | "
                        f"{rate:5.1f} f/s | ETA seg={fmt_time(eta)} | "
                        f"global≈{overall_pct:5.1f}%",
                        flush=True,
                    )

        gaze_rows = [
            aggregate_frame_group(g, participant, name, stype, rf)
            for rf, g in sub.groupby("ref_frame", sort=False)
        ]
        gaze_segment = pd.DataFrame(gaze_rows)

        for c in RAW_COLS:
            if c not in sub.columns:
                sub[c] = np.nan

        # Atomic-ish checkpoint: temp file -> rename.
        sample_tmp = sample_cp.with_suffix(".csv.tmp")
        gaze_tmp = gaze_cp.with_suffix(".csv.tmp")
        meta_tmp = meta_cp.with_suffix(".json.tmp")

        sub[RAW_COLS].to_csv(sample_tmp, index=False)
        gaze_segment.to_csv(gaze_tmp, index=False)

        valid = sub["gaze_valid"]
        gazed_valid = sub.loc[valid, "gazed_objects"].fillna("")

        meta = {
            "segment_name": name,
            "segment_index": segment_index,
            "samples": int(len(sub)),
            "valid": int(valid.sum()),
            "oob": int(sub["gaze_out_of_bounds"].sum()),
            "background": int((gazed_valid == "background").sum()),
            "object_hit": int(
                (
                    (gazed_valid != "")
                    & (gazed_valid != "background")
                    & (gazed_valid != "out_of_bounds")
                ).sum()
            ),
            "coordinate_warning": warning,
            "elapsed_seconds": tic() - seg_start,
        }

        meta_tmp.write_text(json.dumps(meta, indent=2), encoding="utf-8")

        sample_tmp.replace(sample_cp)
        gaze_tmp.replace(gaze_cp)
        meta_tmp.replace(meta_cp)

        seg_elapsed = tic() - seg_start
        session_times.append(seg_elapsed)
        session_done += 1

        avg = sum(session_times) / len(session_times)
        remaining_segments = n_segments - seg_no
        eta_all = avg * remaining_segments

        print(
            f"    [DONE] {name} | {fmt_time(seg_elapsed)} | "
            f"ETA restante≈{fmt_time(eta_all)}",
            flush=True,
        )

        del sub, gaze_segment, jobs, frame_to_indices

    # -------------------------------------------------------------------------
    # Assemblage des checkpoints
    # -------------------------------------------------------------------------
    print("\n[MERGE] Assemblage des checkpoints...", flush=True)

    sample_files = []
    gaze_files = []
    metas = []

    for _, sr in processable.iterrows():
        sp, gp, mp = segment_checkpoint_paths(
            tmp_dir, int(sr["segment_index"]), str(sr["segment_name"])
        )
        if sp.exists() and gp.exists() and mp.exists():
            sample_files.append(sp)
            gaze_files.append(gp)
            metas.append(json.loads(mp.read_text(encoding="utf-8")))

    final_samples = raw_dir / "gaze_samples.csv"
    if final_samples.exists():
        final_samples.unlink()

    wrote = False
    for p in sample_files:
        df_part = pd.read_csv(p, low_memory=False)
        df_part.to_csv(final_samples, mode="a", header=not wrote, index=False)
        wrote = True

    if not wrote:
        pd.DataFrame(columns=RAW_COLS).to_csv(final_samples, index=False)

    gaze_parts = [pd.read_csv(p, low_memory=False) for p in gaze_files]
    gaze_df = pd.concat(gaze_parts, ignore_index=True) if gaze_parts else pd.DataFrame()
    gaze_df.to_csv(out_dir / "gaze.csv", index=False)

    counters = Counter()
    for m in metas:
        counters["samples"] += int(m.get("samples", 0))
        counters["valid"] += int(m.get("valid", 0))
        counters["oob"] += int(m.get("oob", 0))
        counters["background"] += int(m.get("background", 0))
        counters["object_hit"] += int(m.get("object_hit", 0))
        if m.get("coordinate_warning"):
            coordinate_warnings.add(m["coordinate_warning"])

    total_samples = counters["samples"]
    valid = counters["valid"]

    valid_pct = 100 * valid / total_samples if total_samples else 0
    oob_pct = 100 * counters["oob"] / valid if valid else 0
    hit_pct = 100 * counters["object_hit"] / valid if valid else 0
    bg_pct = 100 * counters["background"] / valid if valid else 0

    mapped_segments = int(seg["segment_name"].notna().sum())
    available_segments = len(processable)
    missing_refs = mapped_segments - available_segments

    issues = []
    if missing_refs > 0:
        issues.append("missing_sam_references")
    if len(unmapped) > 0:
        issues.append("unmapped_events")
    if valid_pct < 70:
        issues.append("low_valid_gaze_rate")
    if oob_pct > 5:
        issues.append("high_out_of_bounds_rate")
    if coordinate_warnings:
        issues.append("coordinate_assumption")

    status = "OK" if not issues else "CHECK"

    qc_rows = [
        ("participant", participant),
        ("status", status),
        ("issues", "|".join(issues)),
        ("tobii_rows_total", len(tobii)),
        ("recognized_segments", len(seg)),
        ("mapped_segments", mapped_segments),
        ("segments_with_sam_reference", available_segments),
        ("missing_sam_references", missing_refs),
        ("unmapped_or_event_anomalies", len(unmapped)),
        ("samples_in_processed_segments", total_samples),
        ("valid_gaze_samples", valid),
        ("valid_gaze_pct", round(valid_pct, 3)),
        ("out_of_bounds_samples", counters["oob"]),
        ("out_of_bounds_pct_of_valid", round(oob_pct, 3)),
        ("object_hit_samples", counters["object_hit"]),
        ("object_hit_pct_of_valid", round(hit_pct, 3)),
        ("background_samples", counters["background"]),
        ("background_pct_of_valid", round(bg_pct, 3)),
        ("coordinate_warnings", " || ".join(sorted(coordinate_warnings))),
        ("processing_time", fmt_time(tic() - total_start)),
        ("workers", workers),
        ("completed_checkpoints", len(metas)),
    ]

    pd.DataFrame(qc_rows, columns=["metric", "value"]).to_csv(
        out_dir / "qc_report.csv", index=False
    )

    print(
        f"[QC {participant}] status={status} | valid={valid_pct:.1f}% | "
        f"object={hit_pct:.1f}% | background={bg_pct:.1f}% | "
        f"out={oob_pct:.1f}%",
        flush=True,
    )
    print(f"[TIME] {fmt_time(tic()-total_start)}", flush=True)
    print(f"[OUT]  {out_dir}", flush=True)

    return {
        "participant": participant,
        "status": status,
        "issues": "|".join(issues),
        "valid_gaze_pct": round(valid_pct, 3),
        "object_hit_pct_of_valid": round(hit_pct, 3),
        "background_pct_of_valid": round(bg_pct, 3),
        "out_of_bounds_pct_of_valid": round(oob_pct, 3),
        "processing_time": fmt_time(tic()-total_start),
        "workers": workers,
    }


def discover_participants():
    if not DATASET_RED.exists():
        raise FileNotFoundError(DATASET_RED)

    participants = []
    for d in sorted(DATASET_RED.glob("P*")):
        if not d.is_dir():
            continue
        p = d.name.upper()
        candidate = d / "byTASK" / "MASC" / f"{p}_MASC_Tobii.csv"
        if candidate.exists():
            participants.append(p)
    return participants


def main():
    ap = argparse.ArgumentParser(
        description="MASC Tobii -> SAM V3 optimisée : parallèle, checkpoints, ETA."
    )

    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--participant", help="Ex: P01")
    group.add_argument("--all", action="store_true")

    ap.add_argument(
        "--gaze-mode",
        choices=["auto", "pixels", "normalized"],
        default="auto",
    )
    ap.add_argument("--gaze-source-width", type=float)
    ap.add_argument("--gaze-source-height", type=float)

    ap.add_argument(
        "--workers",
        type=int,
        default=4,
        help="Nombre de frames traitées en parallèle (défaut: 4).",
    )
    ap.add_argument(
        "--progress-every",
        type=int,
        default=50,
        help="Afficher la progression toutes les N frames (défaut: 50).",
    )
    ap.add_argument(
        "--resume",
        action="store_true",
        help="Reprendre depuis les checkpoints de segments déjà terminés.",
    )

    args = ap.parse_args()

    if (args.gaze_source_width is None) ^ (args.gaze_source_height is None):
        ap.error(
            "--gaze-source-width et --gaze-source-height doivent être fournis ensemble"
        )

    if args.workers < 1:
        ap.error("--workers doit être >= 1")

    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    PARTICIPANTS_OUT.mkdir(parents=True, exist_ok=True)

    print("=" * 100, flush=True)
    print("[MASC TOBII SAM V3 OPTI]", flush=True)
    print(f"[PROJECT] {PROJECT_ROOT}", flush=True)
    print(f"[OUTPUT]  {OUTPUT_ROOT}", flush=True)
    print(f"[CPU]     {os.cpu_count()} coeurs logiques | workers demandés={args.workers}", flush=True)
    print("=" * 100, flush=True)

    participants = (
        discover_participants()
        if args.all
        else [norm_participant(args.participant)]
    )

    summaries = []

    for p in participants:
        try:
            summaries.append(
                process_participant(
                    p,
                    args.gaze_mode,
                    args.gaze_source_width,
                    args.gaze_source_height,
                    args.workers,
                    args.progress_every,
                    args.resume,
                )
            )
        except Exception as exc:
            import traceback
            print(f"[ERROR] {p}: {exc}", flush=True)
            traceback.print_exc()
            summaries.append({
                "participant": p,
                "status": "ERROR",
                "issues": str(exc),
            })

    pd.DataFrame(summaries).to_csv(
        OUTPUT_ROOT / "all_participants_summary.csv",
        index=False,
    )

    print("\n[DONE]", flush=True)
    print(
        f"[SUMMARY] {OUTPUT_ROOT / 'all_participants_summary.csv'}",
        flush=True,
    )


if __name__ == "__main__":
    main()